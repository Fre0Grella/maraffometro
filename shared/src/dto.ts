/**
 * What crosses the wire between the Worker and the app. Field names are what
 * the frontend reads; the Worker maps its rows onto them.
 */
import type { Hand, SetTarget, Team } from "./rules";

export interface PlayerDTO {
  id: string;
  name: string;
  emoji: string;
  color: string;
  motto: string;
  /** A profile someone added for a friend who has not signed in yet. */
  isGuest: boolean;
  /** The player deleted their account; only their seat in past matches remains. */
  deleted: boolean;
}

export interface MeDTO extends PlayerDTO {
  email: string | null;
  pictureUrl: string | null;
}

export interface PlayerUpdateDTO {
  name: string;
  emoji: string;
  color: string;
  motto: string;
}

export interface GuestCreateDTO {
  name: string;
}

export interface ClaimCodeDTO {
  code: string;
  expiresAt: string;
}

export interface LeaderboardEntryDTO {
  /** Position by rating, 1-based, provisional players included. */
  rank: number;
  player: PlayerDTO;
  /** Elo-like scale, 1500 is the group average. */
  rating: number;
  /** One standard deviation of the estimate, same scale as rating. */
  uncertainty: number;
  /** Change at the player's last match, if any. */
  lastChange: number | null;
  /** Fewer than 8 finished sets: the position is shown as temporary. */
  provisional: boolean;
  setsPlayed: number;
  setsWon: number;
  matchesPlayed: number;
  matchesWon: number;
}

export interface SetSummaryDTO {
  target: SetTarget;
  score: [number, number];
  winner: Team | null;
}

export interface MatchSummaryDTO {
  id: string;
  playedAt: string;
  /** Indexed by seat: 0 and 2 are team A, 1 and 3 team B. */
  seats: [PlayerDTO, PlayerDTO, PlayerDTO, PlayerDTO];
  sets: SetSummaryDTO[];
  setsWon: [number, number];
  winner: Team | null;
  recordedBy: PlayerDTO;
  voided: boolean;
}

export interface RatingChangeDTO {
  playerId: string;
  before: number;
  after: number;
}

export interface MatchDetailDTO extends MatchSummaryDTO {
  hands: Hand[][];
  ratingChanges: RatingChangeDTO[];
  /** Whether the caller may void this match. */
  canVoid: boolean;
}

export interface MatchSubmitDTO {
  /** Generated by the client, so a retried submission is recognised. */
  id: string;
  playedAt: string;
  /** Player ids by seat. */
  seats: [string, string, string, string];
  sets: { target: SetTarget; hands: Hand[] }[];
}

export interface PartnerStatDTO {
  player: PlayerDTO;
  sets: number;
  setsWon: number;
}

export interface PlayerStatsDTO {
  player: PlayerDTO;
  leaderboard: LeaderboardEntryDTO | null;
  matchesPlayed: number;
  matchesWon: number;
  matchesDrawn: number;
  setsPlayed: number;
  setsWon: number;
  handsPlayed: number;
  maraffas: number;
  maraffasAgainst: number;
  /** Card points per hand while the player's pair was di mano. */
  avgPointsMano: number | null;
  /** Card points per hand while the other pair was di mano. */
  avgPointsFuoriMano: number | null;
  /** Most sets won together. */
  bestPartner: PartnerStatDTO | null;
  /** Lowest set win rate together, among partners with enough sets. */
  worstPartner: PartnerStatDTO | null;
  /** The opponent the player beats least, among those faced enough. */
  nemesis: PartnerStatDTO | null;
  /** Last matches, newest first: W, L or D. */
  form: ("W" | "L" | "D")[];
  recentMatches: MatchSummaryDTO[];
}
