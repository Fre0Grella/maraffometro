/**
 * What crosses the wire between the Worker and the app. Field names are what
 * the frontend reads; the Worker maps its rows onto them.
 */
import type { Hand, SetTarget, Team } from "./rules";

export interface PlayerDTO {
  id: string;
  name: string;
  emoji: string;
  color: string;
  motto: string;
  /** A profile someone added for a friend who has not signed in yet. */
  isGuest: boolean;
  /** The player deleted their account; only their seat in past matches remains. */
  deleted: boolean;
}

export interface MeDTO extends PlayerDTO {
  email: string | null;
  pictureUrl: string | null;
}

export interface PlayerUpdateDTO {
  name: string;
  emoji: string;
  color: string;
  motto: string;
}

export interface GuestCreateDTO {
  name: string;
}

export interface ClaimCodeDTO {
  code: string;
  expiresAt: string;
}

export interface LeaderboardEntryDTO {
  /** Position by rating, 1-based, provisional players included. */
  rank: number;
  player: PlayerDTO;
  /** Elo-like scale, 1500 is the group average. */
  rating: number;
  /** One standard deviation of the estimate, same scale as rating. */
  uncertainty: number;
  /** Change at the player's last match, if any. */
  lastChange: number | null;
  /** Fewer than 8 finished sets: the position is shown as temporary. */
  provisional: boolean;
  setsPlayed: number;
  setsWon: number;
  matchesPlayed: number;
  matchesWon: number;
}

export interface SetSummaryDTO {
  target: SetTarget;
  score: [number, number];
  winner: Team | null;
}

export interface MatchSummaryDTO {
  id: string;
  playedAt: string;
  /** Indexed by seat: 0 and 2 are team A, 1 and 3 team B. */
  seats: [PlayerDTO, PlayerDTO, PlayerDTO, PlayerDTO];
  sets: SetSummaryDTO[];
  setsWon: [number, number];
  winner: Team | null;
  recordedBy: PlayerDTO;
  voided: boolean;
}

export interface RatingChangeDTO {
  playerId: string;
  before: number;
  after: number;
}

export interface MatchDetailDTO extends MatchSummaryDTO {
  hands: Hand[][];
  ratingChanges: RatingChangeDTO[];
  /** The latest deletion proposal, open or settled; null if there never was one. */
  deletion: DeletionProposalDTO | null;
  /** The caller is a registered player of the match and nothing is under way. */
  canProposeDeletion: boolean;
  /** The caller is an admin (ADMIN_EMAILS) and may delete it outright. */
  canAdminVoid: boolean;
}

export type Vote = "yes" | "no";

export interface DeletionProposalDTO {
  id: string;
  status: "open" | "approved" | "rejected";
  proposedBy: PlayerDTO;
  createdAt: string;
  yes: number;
  no: number;
  /** Registered players of the match when the proposal opened. */
  eligible: number;
  /** Yes votes it takes: a strict majority of `eligible`. */
  needed: number;
  myVote: Vote | null;
  /** The caller is one of the voters and the proposal is still open. */
  canVote: boolean;
}

export type NotificationType = "deletion_proposed" | "match_deleted" | "deletion_rejected";

export interface NotificationDTO {
  id: string;
  type: NotificationType;
  createdAt: string;
  read: boolean;
  /** Who caused it, e.g. the player proposing a deletion. */
  actor: PlayerDTO | null;
  match: { id: string; playedAt: string } | null;
}

export interface NotificationsDTO {
  unread: number;
  items: NotificationDTO[];
}

export interface MatchSubmitDTO {
  /** Generated by the client, so a retried submission is recognised. */
  id: string;
  playedAt: string;
  /** Player ids by seat. */
  seats: [string, string, string, string];
  sets: { target: SetTarget; hands: Hand[] }[];
}

export interface PartnerStatDTO {
  player: PlayerDTO;
  sets: number;
  setsWon: number;
}

export interface BestSetDTO {
  matchId: string;
  playedAt: string;
  target: SetTarget;
  /** The player's pair first. */
  score: [number, number];
  margin: number;
}

export interface PlayerStatsDTO {
  player: PlayerDTO;
  leaderboard: LeaderboardEntryDTO | null;
  matchesPlayed: number;
  matchesWon: number;
  matchesDrawn: number;
  setsPlayed: number;
  setsWon: number;
  handsPlayed: number;
  maraffas: number;
  maraffasAgainst: number;
  /** Hands the player's pair won 11–0: every card point, no maraffa. */
  elevenZero: number;
  /** Hands the player's pair won 14–0: every card point plus their maraffa. */
  fourteenZero: number;
  /** The set won by the widest margin; score is the player's pair first. */
  bestSet: BestSetDTO | null;
  /** Card points per hand while the player's pair was di mano. */
  avgPointsMano: number | null;
  /** Card points per hand while the other pair was di mano. */
  avgPointsFuoriMano: number | null;
  /** Most sets won together. */
  bestPartner: PartnerStatDTO | null;
  /** Lowest set win rate together, among partners with enough sets. */
  worstPartner: PartnerStatDTO | null;
  /** The opponent the player beats least, among those faced enough. */
  nemesis: PartnerStatDTO | null;
  /** Last matches, newest first: W, L or D. */
  form: ("W" | "L" | "D")[];
  recentMatches: MatchSummaryDTO[];
}
